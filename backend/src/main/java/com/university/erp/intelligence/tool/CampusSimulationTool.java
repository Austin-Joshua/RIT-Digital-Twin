package com.university.erp.intelligence.tool;

import com.university.erp.intelligence.SourceClass;
import com.university.erp.service.ScenarioSimulationService;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Component;

import java.util.*;

@Component
@RequiredArgsConstructor
public class CampusSimulationTool implements CampusTool {

    private final ScenarioSimulationService scenarioSimulationService;

    @Override
    public String name() {
        return "run_campus_simulation";
    }

    @Override
    public String description() {
        return "Simulates what-if campus scenarios (e.g. intake increases, adding classroom blocks, adjusting bus fleet seats, or HVAC efficiency targets) and compares baseline vs simulated outcomes.";
    }

    @Override
    public List<String> requiredRoles() {
        return List.of("ADMIN", "HOD", "FACULTY");
    }

    @Override
    public ToolResult execute(Map<String, Object> params, String userRole) {
        String scenarioName = params != null && params.get("scenarioName") != null ? String.valueOf(params.get("scenarioName")) : "Proposed Scenario";
        int intakePercent = intParam(params, "intakePercent", 0);
        int extraClassrooms = intParam(params, "extraClassrooms", 0);
        int seatsPerNewClassroom = intParam(params, "seatsPerNewClassroom", 60);
        int busCapacityPercent = intParam(params, "busCapacityPercent", 0);
        int hvacEfficiencyPercent = intParam(params, "hvacEfficiencyPercent", 0);
        int timetableLoadPercent = intParam(params, "timetableLoadPercent", 0);

        Map<String, Object> scenarioInput = new LinkedHashMap<>();
        scenarioInput.put("name", scenarioName);
        scenarioInput.put("intakePercent", intakePercent);
        scenarioInput.put("extraClassrooms", extraClassrooms);
        scenarioInput.put("seatsPerNewClassroom", seatsPerNewClassroom);
        scenarioInput.put("busCapacityPercent", busCapacityPercent);
        scenarioInput.put("hvacEfficiencyPercent", hvacEfficiencyPercent);
        scenarioInput.put("timetableLoadPercent", timetableLoadPercent);

        Map<String, Object> preview = scenarioSimulationService.preview(Map.of("scenarios", List.of(scenarioInput)));

        @SuppressWarnings("unchecked")
        Map<String, Object> current = (Map<String, Object>) preview.getOrDefault("current", Map.of());
        @SuppressWarnings("unchecked")
        List<Map<String, Object>> scenarios = (List<Map<String, Object>>) preview.getOrDefault("scenarios", List.of());
        @SuppressWarnings("unchecked")
        Map<String, Object> recommendation = (Map<String, Object>) preview.getOrDefault("recommendation", Map.of());

        Map<String, Object> simScenario = scenarios.isEmpty() ? Map.of() : scenarios.get(0);
        @SuppressWarnings("unchecked")
        Map<String, Object> changes = simScenario.get("changes") instanceof Map<?, ?> m ? (Map<String, Object>) m : Map.of();

        List<List<Object>> tableRows = new ArrayList<>();
        tableRows.add(List.of("Student Headcount", current.getOrDefault("enrolledStudents", "N/A"), changes.getOrDefault("enrolledStudents", "N/A"), (intakePercent >= 0 ? "+" : "") + intakePercent + "%"));
        tableRows.add(List.of("Classroom Inventory", current.getOrDefault("classrooms", "N/A"), changes.getOrDefault("classrooms", "N/A"), (extraClassrooms >= 0 ? "+" : "") + extraClassrooms + " rooms"));
        tableRows.add(List.of("Formula Energy (kW)", current.getOrDefault("energyDemandKw", "N/A"), changes.getOrDefault("energyDemandKw", "N/A"), changes.getOrDefault("energyDemandDelta", "0 kW")));
        tableRows.add(List.of("Weekly Room Pressure", current.getOrDefault("timetableLoadPercent", "N/A"), changes.getOrDefault("timetableLoadPercent", "N/A"), (timetableLoadPercent >= 0 ? "+" : "") + timetableLoadPercent + "%"));

        String recText = recommendation.get("why") != null ? String.valueOf(recommendation.get("why")) : "Simulation completed.";
        String answer = String.format(
                "Digital Twin What-If Simulation: Scenario '%s' with parameters (Intake: %+d%%, Extra Classrooms: %d, Bus Fleet: %+d%%, HVAC Efficiency: %+d%%). %s Comparison shows projected formula load moving from %s kW to %s kW. (Note: Output is purely SIMULATED via ScenarioSimulationService. It does not alter active campus timetables or databases. Applying real changes requires human administrative approval).",
                scenarioName, intakePercent, extraClassrooms, busCapacityPercent, hvacEfficiencyPercent, recText,
                current.getOrDefault("energyDemandKw", "N/A"), changes.getOrDefault("energyDemandKw", "N/A")
        );

        return ToolResult.builder(name())
                .answer(answer)
                .sourceClass(SourceClass.SIMULATED)
                .because("Generated by ScenarioSimulationService without persisting to authoritative campus state.")
                .addCard("Intake Adjust", (intakePercent >= 0 ? "+" : "") + intakePercent + "%", "students", "SIMULATED", "users")
                .addCard("Room Adjust", (extraClassrooms >= 0 ? "+" : "") + extraClassrooms, "rooms", "SIMULATED", "door")
                .addCard("Projected Energy", changes.getOrDefault("energyDemandKw", "N/A") + " kW", "Formula", "SIMULATED", "bolt")
                .addCard("HVAC Savings", hvacEfficiencyPercent + "%", "efficiency", "SIMULATED", "leaf")
                .table(List.of("Metric", "Current Baseline", "Simulated Output", "Delta / Parameter"), tableRows)
                .addAction("VIEW", "Simulation Lab", "/simulations/lab")
                .addAction("VIEW", "Classroom Allocation", "/classrooms/allocation")
                .addCitation("Digital Twin Governance Protocol, §7.2", "§7.2", "Simulation previews do not execute real campus writes.")
                .build();
    }

    private static int intParam(Map<String, Object> params, String key, int def) {
        if (params == null || params.get(key) == null) return def;
        try {
            return Integer.parseInt(String.valueOf(params.get(key)));
        } catch (Exception e) {
            return def;
        }
    }
}
